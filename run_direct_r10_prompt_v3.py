
import argparse
from concurrent.futures import ThreadPoolExecutor
import json
import re
import string
from collections import Counter
from pathlib import Path

import numpy as np
import requests
import torch
from transformers import AutoTokenizer, AutoModel

# -----------------------------------
# 1. Command-line arguments
# -----------------------------------

parser = argparse.ArgumentParser()

parser.add_argument(
    "--num-questions",
    type=int,
    default=1000,
    help="Number of questions to evaluate"
)

parser.add_argument(
    "--top-k",
    type=int,
    default=5,
    help="Number of chunks to retrieve"
)

parser.add_argument(
    "--embed-batch-size",
    type=int,
    default=32,
    help="Number of questions to embed per Contriever batch"
)

parser.add_argument(
    "--workers",
    type=int,
    default=2,
    help="Number of concurrent Ollama requests"
)

parser.add_argument(
    "--llm-model",
    default="llama3.2:latest",
    help="Ollama model used for answer generation"
)

parser.add_argument(
    "--num-context",
    type=int,
    default=4096,
    help="Maximum context window sent to Ollama"
)

parser.add_argument(
    "--num-predict",
    type=int,
    default=64,
    help="Maximum answer tokens generated by Ollama"
)

args = parser.parse_args()

NUM_QUESTIONS = args.num_questions
TOP_K = args.top_k
EMBED_BATCH_SIZE = args.embed_batch_size
WORKERS = args.workers
LLM_NAME = args.llm_model
NUM_CONTEXT = args.num_context
NUM_PREDICT = args.num_predict

if (
    NUM_QUESTIONS < 1
    or TOP_K < 1
    or EMBED_BATCH_SIZE < 1
    or WORKERS < 1
    or NUM_CONTEXT < 1
    or NUM_PREDICT < 1
):
    parser.error("All arguments must be positive integers.")

MODEL_NAME = "facebook/contriever-msmarco"

PROCESSED = Path(__file__).resolve().parent / "processed"

# -----------------------------------
# 2. Load data
# -----------------------------------

with open(PROCESSED / "questions.jsonl", encoding="utf-8") as f:
    questions = [json.loads(line) for line in f]

with open(PROCESSED / "chunks.jsonl", encoding="utf-8") as f:
    chunks = [json.loads(line) for line in f]

embeddings = np.load(
    PROCESSED / "contriever_embeddings.npy"
)

assert len(embeddings) == len(chunks)

NUM_QUESTIONS = min(NUM_QUESTIONS, len(questions))
TOP_K = min(TOP_K, len(chunks))

print("Total questions available:", len(questions))
print("Questions to evaluate:", NUM_QUESTIONS)
print("Top-K retrieval:", TOP_K)
print("Embedding shape:", embeddings.shape)

# -----------------------------------
# 3. Load Contriever
# -----------------------------------

print("\nLoading Contriever-MSMARCO...")

tokenizer = AutoTokenizer.from_pretrained(MODEL_NAME)
model = AutoModel.from_pretrained(MODEL_NAME)

device = torch.device(
    "mps" if torch.backends.mps.is_available() else "cpu"
)

model = model.to(device)
model.eval()

# -----------------------------------
# 4. Question embedding
# -----------------------------------

def embed_questions(question_texts, batch_size=EMBED_BATCH_SIZE):

    all_embeddings = []

    for start in range(0, len(question_texts), batch_size):
        batch = question_texts[start:start + batch_size]

        inputs = tokenizer(
            batch,
            padding=True,
            truncation=True,
            max_length=512,
            return_tensors="pt"
        )

        inputs = {
            key: value.to(device)
            for key, value in inputs.items()
        }

        with torch.no_grad():
            outputs = model(**inputs)
            mask = inputs["attention_mask"].unsqueeze(-1)
            batch_embeddings = (
                (outputs.last_hidden_state * mask).sum(dim=1)
                / mask.sum(dim=1).clamp(min=1)
            )

        all_embeddings.append(batch_embeddings.cpu().numpy())

    return np.vstack(all_embeddings)


def embed_question(question):

    return embed_questions([question])[0]

# -----------------------------------
# 5. Retrieve top-K chunks
# -----------------------------------

def retrieve(query_vector):

    scores = embeddings @ query_vector

    candidate_indices = np.argpartition(
        scores,
        -TOP_K
    )[-TOP_K:]
    indices = candidate_indices[np.argsort(scores[candidate_indices])[::-1]]

    return [
        {
            "chunk_index": int(index),
            "title": chunks[int(index)]["title"],
            "text": chunks[int(index)]["text"],
            "score": float(scores[index])
        }
        for index in indices
    ]

# -----------------------------------
# 6. Generate answer using Llama 3
# -----------------------------------


def generate_answer(question, retrieved):

    context = "\n\n".join(
        f"[Document {i}]\n"
        f"Title: {chunk['title']}\n"
        f"Content: {chunk['text']}"
        for i, chunk in enumerate(retrieved, 1)
    )

    prompt = f"""Answer the question using only the
retrieved documents.

Combine evidence from different documents when needed.

Return a SHORT answer:
- For a person, return only their name.
- For a company, return only its name.
- For a Yes/No question, return only Yes or No.
- Do not include explanations or introductory phrases.
- If evidence is insufficient, return "Insufficient information.".
- Do not guess.

RETRIEVED DOCUMENTS:
{context}

QUESTION:
{question}

Return the answer in the JSON field named answer.
"""

    answer_schema = {
        "type": "object",
        "properties": {
            "answer": {"type": "string"}
        },
        "required": ["answer"],
        "additionalProperties": False
    }

    request = {
        "model": LLM_NAME,
        "prompt": prompt,
        "format": answer_schema,
        "stream": False,
        "options": {
            "temperature": 0,
            "num_ctx": NUM_CONTEXT,
            "num_predict": NUM_PREDICT
        }
    }

    for attempt in range(2):
        response = requests.post(
            "http://localhost:11434/api/generate",
            json=request,
            timeout=600
        )
        response.raise_for_status()
        raw_answer = response.json().get("response", "").strip()
        try:
            data = json.loads(raw_answer)
            return str(data["answer"]).strip()
        except (json.JSONDecodeError, KeyError, TypeError):
            request["prompt"] = (
                prompt
                + "\nReturn valid compact JSON only, for example: "
                + '{"answer":"Yes"}'
            )

    return "Insufficient information."


# -----------------------------------
# 7. Evaluation metrics
# -----------------------------------

def normalize_answer(text):

    text = str(text or "").lower()

    text = "".join(
        char for char in text
        if char not in string.punctuation
    )

    text = re.sub(r"\b(a|an|the)\b", " ", text)

    return " ".join(text.split())


def exact_match(prediction, reference):

    return int(
        normalize_answer(prediction)
        == normalize_answer(reference)
    )


def calculate_f1(prediction, reference):

    pred_tokens = normalize_answer(prediction).split()
    ref_tokens = normalize_answer(reference).split()

    if not pred_tokens or not ref_tokens:
        return float(pred_tokens == ref_tokens)

    common = Counter(pred_tokens) & Counter(ref_tokens)
    overlap = sum(common.values())

    if overlap == 0:
        return 0.0

    precision = overlap / len(pred_tokens)
    recall = overlap / len(ref_tokens)

    return 2 * precision * recall / (precision + recall)

# -----------------------------------
# 8. Run the experiment
# -----------------------------------

results = []
output_file = (
    PROCESSED
    / (
        f"direct_r{TOP_K}_prompt_v3_"
        f"{re.sub(r'[^A-Za-z0-9._-]+', '_', LLM_NAME)}_"
        f"results_{NUM_QUESTIONS}q.json"
    )
)


if output_file.exists():
    saved = json.loads(output_file.read_text(encoding="utf-8"))
    results = saved.get("results", [])
    print("Resuming from saved questions:", len(results))

completed_numbers = {result["question_number"] for result in results}
pending = [
    (number, item)
    for number, item in enumerate(questions[:NUM_QUESTIONS], 1)
    if number not in completed_numbers
]

question_batch = [item for _, item in pending]
print("\nEmbedding questions in batches...")
question_embeddings = (
    embed_questions([item["query"] for item in question_batch])
    if question_batch
    else np.empty((0, embeddings.shape[1]))
)


def evaluate_question(question_number, item, query_vector):

    question = item["query"]
    reference = item["answer"]

    retrieved = retrieve(query_vector)
    prediction = generate_answer(question, retrieved)

    return {
        "question_number": question_number,
        "question": question,
        "reference_answer": reference,
        "generated_answer": prediction,
        "exact_match": exact_match(prediction, reference),
        "answer_f1": calculate_f1(prediction, reference),
        "retrieved_chunks": [
            {
                "chunk_index": c["chunk_index"],
                "title": c["title"],
                "score": c["score"]
            }
            for c in retrieved
        ]
    }


with ThreadPoolExecutor(max_workers=WORKERS) as executor:
    evaluations = executor.map(
        evaluate_question,
        [number for number, _ in pending],
        question_batch,
        question_embeddings
    )

    for i, result in enumerate(evaluations, 1):

        question = result["question"]
        reference = result["reference_answer"]

        print(f"\n========== QUESTION {i}/{NUM_QUESTIONS} ==========")
        print("Question:", question)
        print("Generated answer:", result["generated_answer"])
        print("Correct answer:", reference)
        print("Exact Match:", result["exact_match"])
        print("Answer F1:", round(result["answer_f1"], 4))

        results.append(result)

        # Save after each question so progress is retained.
        current_em = sum(r["exact_match"] for r in results)
        current_f1 = sum(r["answer_f1"] for r in results)

        data = {
            "model": LLM_NAME,
            "retriever": MODEL_NAME,
            "top_k": TOP_K,
            "questions_evaluated": len(results),
            "exact_match_accuracy": current_em / len(results),
            "average_answer_f1": current_f1 / len(results),
            "results": results
        }

        with open(output_file, "w", encoding="utf-8") as f:
            json.dump(data, f, indent=2, ensure_ascii=False)

# -----------------------------------
# 9. Final evaluation results
# -----------------------------------

correct = sum(r["exact_match"] for r in results)

average_em = correct / len(results)

average_f1 = sum(
    r["answer_f1"] for r in results
) / len(results)

print("\n====================================")
print("DIRECT-R@10 BASELINE EVALUATION")
print("====================================")
print("Questions evaluated:", len(results))
print("Exact matches:", correct)
print("Exact Match Accuracy:", round(average_em * 100, 2), "%")
print("Average Answer F1:", round(average_f1, 4))
print("Average Answer F1 (%):", round(average_f1 * 100, 2), "%")
print("Results saved to:", output_file)
